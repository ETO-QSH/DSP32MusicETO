#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_fonts.py -- generate MIDI/font_tables.h (ASCII 8x8 + CJK 14x14)

    python gen_fonts.py

Reads MIDI/lyrics.lrc to find exactly which CJK glyphs are needed, so the
16x16-era full font is replaced by a small subset (~200 glyphs, ~30 KB).
All paths are relative to this script.
"""
import io
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
LRC = os.path.join(HERE, 'lyrics.lrc')
OUT = os.path.join(HERE, 'font_tables.h')

ASCII_FONT = r'C:\Windows\Fonts\consola.ttf'
CJK_FONT = r'C:\Windows\Fonts\msyh.ttc'
OPEN, CLOSE = '\u3016', '\u3017'          # the brackets that wrap the Chinese line


def ascii_table():
    """95 glyphs, 8x8, column-major, LSB = top row"""
    base = ImageFont.truetype(ASCII_FONT, 10)
    out = []
    for code in range(0x20, 0x7F):
        img = Image.new('L', (8, 8), 0)
        ImageDraw.Draw(img).text((4, 7), chr(code), fill=255, font=base, anchor='ms')
        px = img.load()
        cols = []
        for c in range(8):
            b = 0
            for r in range(8):
                if px[c, r] > 100:
                    b |= (1 << r)
            cols.append(b)
        out.append((code, cols))
    return out


def lyric_chars():
    """chars used by the Chinese lyric lines, in sorted codepoint order"""
    txt = io.open(LRC, 'rb').read().decode('utf-8-sig')
    ts = re.compile(r'\[(\d+):(\d+)(?:[.:](\d+))?\]')
    seen = set()
    for line in txt.splitlines():
        line = line.strip()
        if not line or ts.match(line) is None:
            continue
        body = ts.sub('', line).strip()
        i, j = body.find(OPEN), body.rfind(CLOSE)
        if i >= 0 and j > i:
            for ch in body[i + 1:j].strip():
                if ord(ch) > 0x20:
                    seen.add(ord(ch))
    return sorted(seen)


def cjk_table(codes):
    """14x14 glyphs, row-major, bit0 = leftmost pixel"""
    base = ImageFont.truetype(CJK_FONT, 13)
    out = []
    for code in codes:
        img = Image.new('L', (14, 14), 0)
        ImageDraw.Draw(img).text((7, 7), chr(code), fill=255, font=base, anchor='mm')
        px = img.load()
        rows = []
        for r in range(14):
            v = 0
            for c in range(14):
                if px[c, r] > 100:
                    v |= (1 << c)
            rows.append(v)
        out.append((code, rows))
    return out


def main():
    a = ascii_table()
    c = cjk_table(lyric_chars())

    f = io.open(OUT, 'w', encoding='utf-8', newline='\n')
    f.write('/* font_tables.h -- all glyph tables used by the OLED driver (generated)\n')
    f.write('   * font8x8[95][8] : ASCII 0x20..0x7E, 8x8, column-major, LSB = top row\n')
    f.write('   * font16[]       : %d CJK glyphs, 14x14, row-major, bit0 = leftmost pixel\n' % len(c))
    f.write('   SORTED BY CODE (binary search).  Generated by MIDI/gen_fonts.py */\n')
    f.write('#ifndef FONT_TABLES_H_\n#define FONT_TABLES_H_\n\n')
    f.write('#define FONT_W 14U\n#define FONT_H 14U\n')
    f.write('#define FONT16_COUNT %dU\n\n' % len(c))
    f.write('typedef struct { U16 code; U16 rows[14]; } Glyph14;\n\n')

    f.write('static const U8 font8x8[95][8] = {\n')
    for code, cols in a:
        ch = chr(code)
        esc = '\\"' if ch == '"' else ('\\\\' if ch == '\\' else ch)
        f.write('    { %s },   /* \'%s\' */\n' % (', '.join('0x%02X' % v for v in cols), esc))
    f.write('};\n\n')

    f.write('static const Glyph14 font16[FONT16_COUNT] = {\n')
    for code, rows in c:
        f.write('    { 0x%04X, { %s } },\n' % (code, ','.join('0x%04X' % v for v in rows)))
    f.write('};\n\n#endif\n')
    f.close()

    io.open(os.path.join(HERE, 'lrc_chars.txt'), 'w', encoding='utf-8').write(
        ''.join(chr(x) for x in [k for k, _ in c]))
    print('font_tables.h: %d ascii + %d cjk glyphs, %d bytes'
          % (len(a), len(c), os.path.getsize(OUT)))


if __name__ == '__main__':
    main()
