/* ============================================================================
 *  app.h —— 应用层（把各模块组合成完整的演示功能）
 * ----------------------------------------------------------------------------
 *  功能：
 *    * 数码管显示计数器 0..9999（约 0.4 秒 +1）
 *    * 按 K1..K9 切换 9 种 LED 效果；每按一次计数器清零
 *    * LCD1602 第一行显示当前效果名，第二行显示计数与最近按键
 * ========================================================================== */
#ifndef APP_H_
#define APP_H_

#include "bsp.h"

void app_init(void);        /* 各模块初始化 + 上电自检 + LCD 欢迎信息 */
void app_task(void);        /* 主循环任务（周期性调用） */

/* 调试观测变量（可用调试器 / DSS 脚本读取） */
extern volatile U16 g_value;            /* 数码管计数值 */
extern volatile U16 g_effect;           /* 当前 LED 效果 0..8 */
extern volatile U16 g_phase;            /* 效果步进序号 */
extern volatile U16 g_key;              /* 最近一次按下的键 1..9 */
extern volatile U16 g_key_log[16];      /* 最近 16 次按键（环形记录） */
extern volatile U16 g_key_count;        /* 按键累计次数 */

#endif /* APP_H_ */
