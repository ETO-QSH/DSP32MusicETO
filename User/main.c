/* ============================================================================
 *  main.c —— 程序入口
 * ----------------------------------------------------------------------------
 *  只做两件事：初始化 + 主循环调度；具体功能都在各模块里：
 *      bsp.c       板级底层（时钟/看门狗/FLASH 等待状态）
 *      delay.c     软件延时 + 心跳
 *      led.c       LED 一排 + 9 种效果
 *      smg.c       4 位数码管（74HC164 动态扫描）
 *      key.c       3x3 矩阵按键（消抖 + 按下沿）
 *      lcd1602.c   LCD1602 字符液晶
 *      app.c       应用逻辑（把上面模块组合起来）
 * ========================================================================== */
#include "bsp.h"
#include "app.h"

void main(void)
{
    bsp_init();         /* 时钟 / 看门狗 / (FLASH 版本) Flash 等待状态 */
    app_init();         /* 各外设模块 + 应用初始化 */

    for (;;) {
        app_task();     /* 应用主循环：按键 / 数码管 / LED / 计数 / LCD */
    }
}
